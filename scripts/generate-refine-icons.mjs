// Copies a monochrome icon sprite into Refine UI as tree-shakable React components.
// Usage: node scripts/generate-refine-icons.mjs <path to icons-sprite.svg>
import { readFileSync, writeFileSync } from 'node:fs';

// The sprite draws at a 2px stroke. At 1.75px the icons match the visual weight of lucide's 2px stroke.
const STROKE_SCALE = 0.875;
const OUTPUT_PATH = new URL('../src/icons/refine-icons.ts', import.meta.url);

const spritePath = process.argv[2];

if (!spritePath) {
  console.error('Pass the path to icons-sprite.svg.');
  process.exit(1);
}

const sprite = readFileSync(spritePath, 'utf8');

/**
 * Reads the attributes of one SVG tag into a plain object.
 */
const parseAttributes = (source) => {
  return Object.fromEntries(
    [...source.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, name, value]) => {
      return [name, value];
    }),
  );
};

/**
 * Turns a kebab-case SVG attribute name into the camelCase React prop.
 */
const toPropName = (name) => {
  return name.replaceAll(/-(\w)/g, (_, letter) => {
    return letter.toUpperCase();
  });
};

/**
 * Turns a sprite icon name such as Arrow_Down_LG into the export name RefineIconArrowDownLG.
 */
const toExportName = (name) => {
  return `RefineIcon${name
    .split('_')
    .map((part) => {
      return part[0].toUpperCase() + part.slice(1);
    })
    .join('')}`;
};

/**
 * Flattens one symbol body into path props, folding group attributes into each path and dropping values the root svg already sets.
 */
const toPaths = (body) => {
  const groups = [];
  const paths = [];

  for (const [, closing, tag, rawAttributes, selfClosing] of body.matchAll(/<(\/?)(g|path)\b([^>]*?)(\/?)>/g)) {
    if (tag === 'g') {
      if (closing) {
        groups.pop();
      } else if (!selfClosing) {
        groups.push(parseAttributes(rawAttributes));
      }
      continue;
    }

    if (closing) {
      continue;
    }

    const attributes = Object.assign({}, ...groups, parseAttributes(rawAttributes));
    const path = {};

    for (const [name, value] of Object.entries(attributes)) {
      if (name === 'id') continue;
      if (name === 'stroke' && value === 'currentColor') continue;
      if (name === 'fill' && value === 'none') continue;
      if ((name === 'stroke-linecap' || name === 'stroke-linejoin') && value === 'round') continue;
      if (name === 'stroke-width') {
        if (value !== '2') path.strokeWidth = Number((Number(value) * STROKE_SCALE).toFixed(3));
        continue;
      }
      path[toPropName(name)] = value;
    }

    // The root svg strokes in currentColor, so a fill-only path must opt out explicitly.
    if (!('stroke' in attributes)) path.stroke = 'none';
    // A stroked path without a join drew mitred corners in the sprite, so it keeps them here.
    if ('stroke' in attributes && !('stroke-linejoin' in attributes)) path.strokeLinejoin = 'miter';
    if ('stroke' in attributes && !('stroke-linecap' in attributes)) path.strokeLinecap = 'butt';

    // The sprite repeats some dot paths verbatim. A repeat draws nothing new and would collide as a React key.
    if (
      !paths.some((existing) => {
        return JSON.stringify(existing) === JSON.stringify(path);
      })
    ) {
      paths.push(path);
    }
  }

  return paths;
};

const icons = new Map();
const skipped = new Set();

for (const [, rawAttributes, body] of sprite.matchAll(/<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g)) {
  const { id, viewBox } = parseAttributes(rawAttributes);

  // Raster 3D illustrations and multi-colour flags cannot follow currentColor, so they stay out of this set.
  if (body.includes('<image') || /="#/.test(body) || body.includes('url(#')) {
    skipped.add(id);
    continue;
  }

  icons.set(id, {
    paths: toPaths(body),
    viewBox,
  });
}

const lines = [...icons.entries()]
  .sort(([a], [b]) => {
    return a.localeCompare(b);
  })
  .map(([name, { paths, viewBox }]) => {
    return `export const ${toExportName(name)} = /* @__PURE__ */ createRefineIcon('${name}', '${viewBox}', ${JSON.stringify(paths)});`;
  });

writeFileSync(
  OUTPUT_PATH,
  [
    '// Generated by scripts/generate-refine-icons.mjs from the icons sprite. Do not edit by hand.',
    "import { createRefineIcon } from './create-refine-icon';",
    '',
    ...lines,
    '',
  ].join('\n'),
);

console.log(`Wrote ${icons.size} icons. Skipped ${skipped.size}: ${[...skipped].join(', ')}`);
